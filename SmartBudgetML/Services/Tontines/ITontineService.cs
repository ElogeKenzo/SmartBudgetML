using SmartBudgetML.Models;

namespace SmartBudgetML.Services.Tontines;

public sealed record TontineMemberDraft(string Name, int TurnOrder, bool IsCurrentUser);

/// <summary>What the "new tontine" screen sends; checked by <see cref="TontineDraftValidator"/>.</summary>
public sealed class TontineDraft
{
    public string Name { get; set; } = string.Empty;
    public decimal ContributionAmount { get; set; }
    public TontineFrequency Frequency { get; set; } = TontineFrequency.Monthly;
    public DateTime StartDate { get; set; } = DateTime.Today;
    public List<TontineMemberDraft> Members { get; set; } = new();
}

/// <summary>Each value has a translation key "TontineError_{value}".</summary>
public enum TontineValidationError
{
    NameRequired,
    AmountNotPositive,
    AmountNotWhole,
    TooFewMembers,
    MemberNameRequired,
    TurnOrdersNotUnique,
    TurnOrderOutOfRange,
    CurrentUserMissing
}

public sealed class TontineValidationException : Exception
{
    public TontineValidationException(IReadOnlyList<TontineValidationError> errors)
        : base("Invalid tontine: " + string.Join(", ", errors))
    {
        Errors = errors;
    }

    public IReadOnlyList<TontineValidationError> Errors { get; }
}

public enum TontineRecordOutcome
{
    Recorded,
    AlreadyRecorded
}

public sealed record TontineMemberStatus(TontineMember Member, bool HasPaidCurrentRound);

public sealed record TontineLateItem(int RoundNumber, DateTime DueDate, TontineMember Member);

/// <summary>Everything the detail screen shows, read from the database.</summary>
public sealed record TontineDetails(
    Tontine Tontine,
    IReadOnlyList<TontineMember> Members,
    IReadOnlyList<TontineRound> Rounds,
    IReadOnlyList<TontineContribution> Contributions,
    TontineRound? CurrentRound,
    TontineMember? CurrentBeneficiary,
    IReadOnlyList<TontineMemberStatus> CurrentRoundStatuses,
    IReadOnlyList<TontineLateItem> LateContributions,
    TontineUserSummary Summary)
{
    public TontineMember? CurrentUser => Members.FirstOrDefault(m => m.IsCurrentUser);

    public bool IsFinished => CurrentRound is null;

    public bool HasUserPaidCurrentRound =>
        CurrentRoundStatuses.Any(s => s.Member.IsCurrentUser && s.HasPaidCurrentRound);

    public bool IsUserCurrentBeneficiary => CurrentBeneficiary?.IsCurrentUser == true;
}

/// <summary>A contribution the user still owes, due within <see cref="TontineService.DueSoonDays"/> days or already late.</summary>
public sealed record TontineDue(
    int TontineId,
    string TontineName,
    int RoundNumber,
    decimal Amount,
    DateTime DueDate,
    bool IsOverdue);

public sealed record TontineOverview(
    int ActiveCount,
    DateTime? NextDueDate,
    IReadOnlyList<TontineDue> Dues);

/// <summary>
/// Tontines stored in the database (lot 8E, N1): creation, members and turn order, rounds generated by
/// <see cref="TontineCalculator"/>, contributions and pot payouts linked to expenses without duplicates.
/// </summary>
public interface ITontineService
{
    Task<IReadOnlyList<Tontine>> GetTontinesAsync();

    Task<TontineDetails?> GetDetailsAsync(int tontineId, DateTime today);

    /// <summary>Throws <see cref="TontineValidationException"/> when the draft is invalid.</summary>
    Task<int> CreateAsync(TontineDraft draft);

    /// <summary>Renames the tontine and changes the contribution for the rounds not yet paid out.</summary>
    Task UpdateAsync(int tontineId, string name, decimal contributionAmount);

    /// <summary>Deletes the tontine, its members, rounds and contributions. Expenses already booked stay.</summary>
    Task DeleteAsync(int tontineId);

    /// <summary>Marks the member as gone and rebuilds the rounds not yet paid out.</summary>
    Task WithdrawMemberAsync(int tontineId, int memberId);

    /// <summary>
    /// Idempotent: a second call for the same tontine, round and member changes nothing.
    /// When the member is the user, the linked expense is created once.
    /// </summary>
    Task<TontineRecordOutcome> RecordContributionAsync(int tontineId, int roundNumber, int memberId, DateTime date);

    /// <summary>
    /// Marks the pot of the round as paid out. When the user is the beneficiary, books an exceptional
    /// income in "transfers_received" once, left out of the income average.
    /// </summary>
    Task<TontineRecordOutcome> RecordPayoutAsync(int tontineId, int roundNumber, DateTime date);

    /// <summary>Active tontines, next due date and the contributions to pay, computed when the home screen opens.</summary>
    Task<TontineOverview> GetOverviewAsync(DateTime today);
}
